#!/usr/bin/env bash
# The Bastion — CapRover production entrypoint.
# vim: set filetype=sh ts=4 sw=4 sts=4 et:
#
# Responsibilities (in order):
#   1. Restore persisted UNIX identity + ssh host keys into the ephemeral rootfs
#      BEFORE anything reads them (you cannot safely bind-mount /etc/passwd etc).
#   2. Decide new-install vs upgrade by probing persisted state, run bin/admin/install
#      accordingly (idempotent), with --no-regen-hostkeys once host keys exist.
#   3. Wire remote syslog from a CapRover template variable, if provided.
#   4. Start syslog-ng, cron, sshd and supervise them (PID 1, reaps + restarts).
#
# CapRover persistent dirs (configured on the app) are mounted at:
#   /var/bastion-persist/home     -> canonical /home
#   /var/bastion-persist/etc      -> canonical /etc/bastion
#   /var/bastion-persist/identity -> passwd/shadow/group/gshadow snapshots
#   /var/bastion-persist/gnupg    -> canonical /root/.gnupg
#   /var/bastion-persist/hostkeys -> /etc/ssh/ssh_host_* snapshots
#   /var/bastion-persist/logs     -> /var/log/bastion
set -euo pipefail

PERSIST=/var/bastion-persist
IDENTITY_FILES=(passwd shadow group gshadow)
log() { echo "[entrypoint] $*" >&2; }

# ---- 0. ensure persistent subdirs exist -----------------------------------
for d in home etc identity gnupg hostkeys logs; do
    mkdir -p "$PERSIST/$d"
done

# ---- 1. bind canonical dirs to persisted storage --------------------------
# /home and /etc/bastion and /root/.gnupg and /var/log/bastion are whole dirs,
# so a bind mount is safe (no file-rename trap). We bind them here rather than
# relying on CapRover mapping them directly to the canonical paths, which keeps
# all persistence under one declared volume root.
bind_dir() {
    local src="$1" dst="$2"
    mkdir -p "$src" "$dst"
    if ! mountpoint -q "$dst"; then
        mount --bind "$src" "$dst" 2>/dev/null || {
            # no CAP_SYS_ADMIN: fall back to symlink if dst is empty/absent
            if [ ! -e "$dst" ] || [ -z "$(ls -A "$dst" 2>/dev/null)" ]; then
                rm -rf "$dst"; ln -s "$src" "$dst"
            fi
        }
    fi
}
bind_dir "$PERSIST/home"  /home
bind_dir "$PERSIST/etc"   /etc/bastion
bind_dir "$PERSIST/gnupg" /root/.gnupg
bind_dir "$PERSIST/logs"  /var/log/bastion
chmod 700 /root/.gnupg || true

# ---- 2. restore identity files + host keys (the single-file trap) ---------
# Identity DBs CANNOT be bind-mounted (shadow-utils renames over them). Instead
# we snapshot-restore on boot and sync-back on change (see sync hooks below).
FIRST_BOOT=0
if [ -f "$PERSIST/identity/passwd" ]; then
    log "restoring persisted identity files"
    for f in "${IDENTITY_FILES[@]}"; do
        [ -f "$PERSIST/identity/$f" ] && cp -a "$PERSIST/identity/$f" "/etc/$f"
    done
else
    FIRST_BOOT=1
    log "no persisted identity yet -> first boot"
fi

if ls "$PERSIST"/hostkeys/ssh_host_* >/dev/null 2>&1; then
    log "restoring persisted ssh host keys"
    cp -a "$PERSIST"/hostkeys/ssh_host_* /etc/ssh/
    HAVE_HOSTKEYS=1
else
    HAVE_HOSTKEYS=0
fi

# sync-back helper: persist identity + host keys after install mutates them.
sync_identity() {
    for f in "${IDENTITY_FILES[@]}"; do
        cp -a "/etc/$f" "$PERSIST/identity/$f" 2>/dev/null || true
    done
    cp -a /etc/ssh/ssh_host_* "$PERSIST/hostkeys/" 2>/dev/null || true
}

# ---- 3. run install: new-install only on a truly fresh volume -------------
# After the first successful new-install, every boot is an idempotent --upgrade.
if [ "$FIRST_BOOT" = 1 ] && [ "$HAVE_HOSTKEYS" = 0 ]; then
    log "running: install --new-install"
    /opt/bastion/bin/admin/install --new-install
else
    # upgrade mode; never regenerate host keys we already persist.
    log "running: install --upgrade --no-regen-hostkeys"
    /opt/bastion/bin/admin/install --upgrade --no-regen-hostkeys
fi
# always run the ACL repair the stock entrypoint does (registry push drops ACLs)
/opt/bastion/bin/admin/install --minimal
sync_identity

# ---- 4. remote syslog from CapRover template var --------------------------
# REMOTE_SYSLOG_HOST / REMOTE_SYSLOG_PORT / REMOTE_SYSLOG_PROTO are injected by
# the one-click app spec ($$cap_syslog_host etc). Empty host => local only.
REMOTE_SYSLOG_HOST="${REMOTE_SYSLOG_HOST:-}"
REMOTE_SYSLOG_PORT="${REMOTE_SYSLOG_PORT:-514}"
REMOTE_SYSLOG_PROTO="${REMOTE_SYSLOG_PROTO:-tcp}"   # tcp|udp
if [ -n "$REMOTE_SYSLOG_HOST" ]; then
    log "configuring remote syslog -> $REMOTE_SYSLOG_HOST:$REMOTE_SYSLOG_PORT/$REMOTE_SYSLOG_PROTO"
    cat > /etc/syslog-ng/conf.d/30-bastion-remote.conf <<EOF
# Auto-generated by entrypoint from CapRover template vars. Forwards the SAME
# bastion/scripts streams defined in 20-bastion.conf.dist to a remote collector.
destination d_bastion_remote {
    ${REMOTE_SYSLOG_PROTO}("$REMOTE_SYSLOG_HOST" port($REMOTE_SYSLOG_PORT));
};
log { source(s_src); parser(p_bastion_msg); filter(f_bastion);         destination(d_bastion_remote); };
log { source(s_src);                         filter(f_bastion_scripts); destination(d_bastion_remote); };
EOF
else
    log "no REMOTE_SYSLOG_HOST set -> local syslog only"
    rm -f /etc/syslog-ng/conf.d/30-bastion-remote.conf
fi

# ---- 5. supervise sshd + syslog-ng + cron ---------------------------------
# Minimal PID-1 supervisor: start the three daemons in the foreground where
# possible, restart any that die, and forward SIGTERM for a clean stop.
pids=()
start_syslog() { syslog-ng -F &  pids+=($!); log "syslog-ng pid $!"; }
start_cron()   { cron -f &       pids+=($!); log "cron pid $!"; }
start_sshd()   { /usr/sbin/sshd -D -e & pids+=($!); log "sshd pid $!"; }

term() { log "SIGTERM -> stopping"; kill "${pids[@]}" 2>/dev/null || true; sync_identity; exit 0; }
trap term TERM INT

start_syslog; sleep 1
start_cron
start_sshd

log "The Bastion is up. SSH on container :22 (host 2222 via host-mode publish)."
# Supervise: block until ANY supervised child exits. `wait -n` returns as soon as
# one of them dies; whichever it was, we treat the loss of any core daemon as fatal,
# persist state, stop the rest, and exit non-zero so Swarm recreates the task clean.
# (We deliberately do NOT hot-restart individual daemons in-place: a clean container
# recreate re-runs the install/ACL-repair/identity-restore sequence above, which is
# the known-good state, rather than leaving a half-initialised container running.)
wait -n || ec=$?
ec="${ec:-0}"
log "a supervised daemon exited (status $ec) -> syncing state and exiting for restart"
sync_identity
kill "${pids[@]}" 2>/dev/null || true
exit 1
